local fixture = dofile("tests/fixtures/forever_diagnostics.lua")
local addon = fixture.Load()
local api, secret, restricted = fixture.API()
local safe = addon.SafeValues.New(api)

assert(safe:Classify(secret, "number") == "secret")
assert(safe:Field(restricted, "any", "number") == "restricted")
assert(safe:Field(secret, "any", "number") == "secret")
assert(safe:Classify(nil, "number") == "missing")
assert(safe:Classify("7", "number") == "unexpected")
assert(safe:Classify(0 / 0, "number") == "unexpected")
local state, zero = safe:Classify(0, "number")
assert(state == "readable" and zero == 0)
local boolState, bool = safe:Classify(false, "boolean")
assert(boolState == "readable" and bool == false)
assert(safe:Call(nil, "number") == "unavailable")
assert(safe:Call(function()
    error("sensitive error")
end, "number") == "failed")
assert(addon.SafeValues.New({}):Classify(secret, "number") == "guard-unavailable")

local visited = {}
local scan = safe:Each({ {}, secret, {}, {} }, 3, function(rowState)
    visited[#visited + 1] = rowState
end)
assert(scan.capped and scan.lowerBound == 4 and scan.scanned == 3)
assert(visited[2] == "secret")
assert(safe:Each({}, 3, function()
    error("unexpected row")
end).state == "empty")
print("Safe value tests passed")
